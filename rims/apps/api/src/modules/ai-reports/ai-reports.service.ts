import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import * as https from 'https';
import { PrismaService } from '../prisma/prisma.service';
import { ReportsService } from '../reports/reports.service';

@Injectable()
export class AiReportsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly reportsService: ReportsService,
    private readonly configService: ConfigService,
  ) {}

  async generateExecutiveSummary(
    tenantId: string,
    periodStart: string,
    periodEnd: string,
  ): Promise<{
    summary: string | null;
    sourceData: unknown;
    isAiGenerated: boolean;
    generatedAt: Date;
    disclaimer: string;
  }> {
    // 1. Gather structured data
    const [overview, portfolio, cycles] = await Promise.all([
      this.reportsService.executiveOverview(tenantId),
      this.reportsService.researchPortfolio(tenantId, {
        dateFrom: periodStart,
        dateTo: periodEnd,
      }),
      this.prisma.performanceCycle.findMany({
        where: { tenantId, status: 'ACTIVE' },
        take: 3,
        orderBy: { startDate: 'desc' },
      }),
    ]);

    const performanceSummaries = await Promise.all(
      cycles.map((c: { id: string }) => this.reportsService.performanceSummary(tenantId, c.id)),
    );

    const sourceData = {
      periodStart,
      periodEnd,
      executiveOverview: overview,
      researchPortfolio: portfolio,
      performanceSummaries,
    };

    // 2. Read AI config
    const apiKey = this.configService.get<string>('AI_PROVIDER_API_KEY');
    const model = this.configService.get<string>('AI_MODEL') ?? 'gpt-4o-mini';

    let summary: string | null = null;
    let isAiGenerated = false;

    // 3. Call OpenAI if API key is configured
    if (apiKey) {
      try {
        summary = await this.callOpenAI(apiKey, model, sourceData);
        isAiGenerated = true;
      } catch (err) {
        // Never log the API key. Log only the error message.
        console.error(
          `[AiReportsService] OpenAI request failed: ${(err as Error).message}`,
        );
      }
    }

    // 4. Return result
    return {
      summary,
      sourceData,
      isAiGenerated,
      generatedAt: new Date(),
      disclaimer:
        'This summary was generated by AI from RIMS platform data. Verify figures against source records before use in official reports.',
    };
  }

  private callOpenAI(
    apiKey: string,
    model: string,
    sourceData: unknown,
  ): Promise<string> {
    return new Promise((resolve, reject) => {
      const body = JSON.stringify({
        model,
        max_tokens: 1500,
        temperature: 0.2,
        messages: [
          {
            role: 'system',
            content:
              'You are an institutional analytics assistant for RIMS. Summarise the provided structured data as a factual institutional report. Do not invent figures not present in the data. Do not make judgements about individual employees. Indicate uncertainty where data is incomplete. Label this summary as AI-generated.',
          },
          {
            role: 'user',
            content: JSON.stringify(sourceData),
          },
        ],
      });

      const options: https.RequestOptions = {
        hostname: 'api.openai.com',
        path: '/v1/chat/completions',
        method: 'POST',
        headers: {
          Authorization: `Bearer ${apiKey}`,
          'Content-Type': 'application/json',
          'Content-Length': Buffer.byteLength(body),
        },
      };

      const req = https.request(options, (res) => {
        let data = '';
        res.on('data', (chunk: Buffer) => {
          data += chunk.toString();
        });
        res.on('end', () => {
          try {
            const parsed = JSON.parse(data) as {
              choices?: { message?: { content?: string } }[];
              error?: { message?: string };
            };

            if (parsed.error?.message) {
              reject(new Error(parsed.error.message));
              return;
            }

            const content = parsed.choices?.[0]?.message?.content;
            if (!content) {
              reject(new Error('Empty response from AI provider'));
              return;
            }
            resolve(content);
          } catch (parseErr) {
            reject(parseErr instanceof Error ? parseErr : new Error(String(parseErr)));
          }
        });
      });

      req.on('error', (err) => reject(err));
      req.write(body);
      req.end();
    });
  }
}
