  /**
   * Contact form submission.
   * Rate limiting: handled at Throttler level (5/min per IP via ThrottlerGuard
   * applied globally in the app; additional rate limit logic can be added here).
   * NEVER returns submission data — returns only { success: true }.
   */
  @Post('contact')
  async submitContact(
    @Req() req: Request,
    @Body() dto: CreateContactSubmissionDto,
  ) : Promise<unknown> {
    if (!dto.consentGiven) {
      throw new BadRequestException('Consent is required');
    }

    const hostname = this.getHostname(req);
    const { websiteId, tenantId } =
      await this.publicApiService.resolveTenantFromHostname(hostname);
    return this.publicApiService.submitContact(websiteId, tenantId, dto);
  }
