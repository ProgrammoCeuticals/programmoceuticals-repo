/**
 * Standard API error contract.
 * Source: ECTD_BACKEND_IMPLEMENTATION.md § 35
 *
 * All API errors use this shape. HTTP status codes: 400, 401, 403, 404, 409, 422, 429, 500.
 */
export interface ApiErrorBody {
  error: {
    code: string;
    message: string;
    category: ApiErrorCategory;
    details?: Record<string, unknown>;
    correlationId?: string;
  };
}

export type ApiErrorCategory =
  | "DOMAIN"
  | "VALIDATION"
  | "AUTHORIZATION"
  | "NOT_FOUND"
  | "CONFLICT"
  | "REGULATORY"
  | "INFRASTRUCTURE";

