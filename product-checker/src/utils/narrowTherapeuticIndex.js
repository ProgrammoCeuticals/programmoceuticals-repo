import { expandSynonyms } from './synonyms.js';

const norm = (v) => v.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

// Word-boundary exact match: every word in the NTI drug name must appear as a
// whole word in the search term (or vice versa). This prevents "am" matching
// "amikacin", "amiodarone", etc.
function ntiTermMatches(searchTerm, drugName) {
  const termWords = new Set(norm(searchTerm).split(/\s+/).filter(Boolean));
  const drugWords = norm(drugName).split(/\s+/).filter(Boolean);
  if (!drugWords.length || !termWords.size) return false;
  // All drug words must be present as whole words in the search term
  return drugWords.every((w) => termWords.has(w));
}

function buildSearchTerms(primaryName, extras) {
  const raw = [primaryName, ...(Array.isArray(extras) ? extras : [extras])]
    .filter(Boolean)
    .map((t) => t.toLowerCase());
  // Expand each term with its synonyms
  const expanded = new Set();
  for (const t of raw) {
    for (const s of expandSynonyms(t)) expanded.add(s);
  }
  return Array.from(expanded);
}

export const hasNarrowTherapeuticIndex = (productName, activeIngredients = []) => {
  const terms = buildSearchTerms(productName, activeIngredients);
  if (!terms.length) return false;
  return NTI_DRUG_LIST.some((drug) =>
    terms.some((t) => ntiTermMatches(t, drug))
  );
};

export const getMatchedNTIDrugs = (productName, activeIngredients = []) => {
  const terms = buildSearchTerms(productName, activeIngredients);
  if (!terms.length) return [];
  return NTI_DRUG_LIST.filter((drug) =>
    terms.some((t) => ntiTermMatches(t, drug))
  );
};